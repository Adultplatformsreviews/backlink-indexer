-- Additive indexer-network schema. The app applies the same changes on startup
-- for SQLite and Postgres. Do not drop or rename existing columns.
-- Postgres 11+ accepts ADD COLUMN IF NOT EXISTS. The Python migrator checks
-- information_schema first, which is what production runs.

CREATE TABLE IF NOT EXISTS hub_domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname TEXT NOT NULL UNIQUE,
    indexnow_key TEXT NOT NULL DEFAULT '',
    indexnow_verified_at TEXT NOT NULL DEFAULT '',
    google_push_enabled INTEGER NOT NULL DEFAULT 0,
    gcp_projects_json_encrypted TEXT NOT NULL DEFAULT '',
    daily_quota_used TEXT NOT NULL DEFAULT '',
    last_push_at TEXT NOT NULL DEFAULT '',
    last_error TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS hub_pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hub_domain_id BIGINT,
    slug TEXT NOT NULL,
    url_ids_json TEXT NOT NULL DEFAULT '[]',
    intro_text TEXT NOT NULL DEFAULT '',
    pushes_count INTEGER NOT NULL DEFAULT 0,
    last_pushed_at TEXT NOT NULL DEFAULT '',
    bot_hits_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_id BIGINT,
    type TEXT NOT NULL,
    payload_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider TEXT NOT NULL,
    config_encrypted TEXT NOT NULL DEFAULT '',
    enabled INTEGER NOT NULL DEFAULT 1,
    UNIQUE (user_id, provider)
);

CREATE TABLE IF NOT EXISTS serp_cache (
    cache_key TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    created_at TEXT NOT NULL
);

