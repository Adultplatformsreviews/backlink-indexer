-- Daily credit allowance history. The app applies the same table on startup
-- for SQLite and Postgres. Do not drop or rename existing columns.
-- One row per account per Asia/Karachi day makes the refill idempotent.

CREATE TABLE IF NOT EXISTS credit_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day TEXT NOT NULL,
    kind TEXT NOT NULL,
    amount INTEGER NOT NULL,
    balance_before INTEGER NOT NULL,
    balance_after INTEGER NOT NULL,
    target INTEGER NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    UNIQUE (user_id, day, kind)
);
