"""Additive tables and columns for the indexer network. Nothing is dropped."""

from __future__ import annotations

URL_COLUMNS = {
    "normalized_url": "TEXT NOT NULL DEFAULT ''",
    "host": "TEXT NOT NULL DEFAULT ''",
    "kind": "TEXT NOT NULL DEFAULT ''",
    "precheck_json": "TEXT NOT NULL DEFAULT ''",
    "status": "TEXT NOT NULL DEFAULT 'queued'",
    "hub_page_id": "INTEGER",
    "submitted_at": "TEXT NOT NULL DEFAULT ''",
    "last_check_at": "TEXT NOT NULL DEFAULT ''",
    "next_check_at": "TEXT NOT NULL DEFAULT ''",
    "indexed_at": "TEXT NOT NULL DEFAULT ''",
    "credits_held": "INTEGER NOT NULL DEFAULT 0",
    "credits_state": "TEXT NOT NULL DEFAULT ''",
    "refunded_at": "TEXT NOT NULL DEFAULT ''",
}


def _tables(postgres: bool) -> list[str]:
    if postgres:
        return [
            """CREATE TABLE IF NOT EXISTS hub_domains (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                hostname TEXT NOT NULL UNIQUE,
                indexnow_key TEXT NOT NULL DEFAULT '',
                indexnow_verified_at TEXT NOT NULL DEFAULT '',
                google_push_enabled INTEGER NOT NULL DEFAULT 0,
                gcp_projects_json_encrypted TEXT NOT NULL DEFAULT '',
                daily_quota_used TEXT NOT NULL DEFAULT '',
                last_push_at TEXT NOT NULL DEFAULT '',
                last_error TEXT NOT NULL DEFAULT ''
            )""",
            """CREATE TABLE IF NOT EXISTS hub_pages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                hub_domain_id BIGINT,
                slug TEXT NOT NULL,
                url_ids_json TEXT NOT NULL DEFAULT '[]',
                intro_text TEXT NOT NULL DEFAULT '',
                pushes_count INTEGER NOT NULL DEFAULT 0,
                last_pushed_at TEXT NOT NULL DEFAULT '',
                bot_hits_json TEXT NOT NULL DEFAULT '{}',
                created_at TEXT NOT NULL DEFAULT ''
            )""",
            """CREATE TABLE IF NOT EXISTS events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                url_id BIGINT,
                type TEXT NOT NULL,
                payload_json TEXT NOT NULL DEFAULT '{}',
                created_at TEXT NOT NULL
            )""",
            """CREATE TABLE IF NOT EXISTS connections (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                provider TEXT NOT NULL,
                config_encrypted TEXT NOT NULL DEFAULT '',
                enabled INTEGER NOT NULL DEFAULT 1,
                UNIQUE (user_id, provider)
            )""",
            """CREATE TABLE IF NOT EXISTS serp_cache (
                cache_key TEXT PRIMARY KEY,
                payload TEXT NOT NULL,
                created_at TEXT NOT NULL
            )""",
        ]
    return [
        """CREATE TABLE IF NOT EXISTS hub_domains (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            hostname TEXT NOT NULL UNIQUE,
            indexnow_key TEXT NOT NULL DEFAULT '',
            indexnow_verified_at TEXT NOT NULL DEFAULT '',
            google_push_enabled INTEGER NOT NULL DEFAULT 0,
            gcp_projects_json_encrypted TEXT NOT NULL DEFAULT '',
            daily_quota_used TEXT NOT NULL DEFAULT '',
            last_push_at TEXT NOT NULL DEFAULT '',
            last_error TEXT NOT NULL DEFAULT ''
        )""",
        """CREATE TABLE IF NOT EXISTS hub_pages (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            hub_domain_id INTEGER,
            slug TEXT NOT NULL,
            url_ids_json TEXT NOT NULL DEFAULT '[]',
            intro_text TEXT NOT NULL DEFAULT '',
            pushes_count INTEGER NOT NULL DEFAULT 0,
            last_pushed_at TEXT NOT NULL DEFAULT '',
            bot_hits_json TEXT NOT NULL DEFAULT '{}',
            created_at TEXT NOT NULL DEFAULT ''
        )""",
        """CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            url_id INTEGER,
            type TEXT NOT NULL,
            payload_json TEXT NOT NULL DEFAULT '{}',
            created_at TEXT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS connections (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            provider TEXT NOT NULL,
            config_encrypted TEXT NOT NULL DEFAULT '',
            enabled INTEGER NOT NULL DEFAULT 1,
            UNIQUE (user_id, provider)
        )""",
        """CREATE TABLE IF NOT EXISTS serp_cache (
            cache_key TEXT PRIMARY KEY,
            payload TEXT NOT NULL,
            created_at TEXT NOT NULL
        )""",
    ]


_INDEXES = (
    "CREATE INDEX IF NOT EXISTS idx_urls_status ON urls(status)",
    "CREATE INDEX IF NOT EXISTS idx_urls_norm ON urls(project_id, normalized_url)",
    "CREATE INDEX IF NOT EXISTS idx_urls_next_check ON urls(next_check_at)",
    "CREATE INDEX IF NOT EXISTS idx_hub_pages_domain ON hub_pages(hub_domain_id, slug)",
    "CREATE INDEX IF NOT EXISTS idx_events_url ON events(url_id)",
    "CREATE INDEX IF NOT EXISTS idx_events_type ON events(type, created_at)",
    "CREATE INDEX IF NOT EXISTS idx_connections_user ON connections(user_id, provider)",
)


def apply_indexer_schema(conn) -> None:
    from .database import _add_columns

    for statement in _tables(conn.postgres):
        conn.execute(statement)
    _add_columns(conn, "urls", URL_COLUMNS)
    for statement in _INDEXES:
        conn.execute(statement)
